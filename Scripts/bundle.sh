#!/bin/bash
# Builds a standalone "Christmas Tree.app" at build/Christmas Tree.app.
#   Scripts/bundle.sh            build only
#   Scripts/bundle.sh --install  also copy to /Applications and launch it
set -euo pipefail
cd "$(dirname "$0")/.."

APP_NAME=ChristmasTree               # executable and SwiftPM product
BUNDLE_NAME="Christmas Tree"          # what Finder and the Dock show
APP="build/$BUNDLE_NAME.app"

swift build -c release
BIN_DIR=$(swift build -c release --show-bin-path)

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$APP/Contents/Frameworks"
cp "$BIN_DIR/$APP_NAME" "$APP/Contents/MacOS/$APP_NAME"
cp Scripts/Info.plist "$APP/Contents/Info.plist"

# Localizations: SwiftPM packs the .lproj string tables into a resource
# bundle; the app resolves it from Contents/Resources by hand (see
# Sources/ChristmasTree/Localization.swift).
cp -R "$BIN_DIR/${APP_NAME}_${APP_NAME}.bundle" "$APP/Contents/Resources/"

# Embed Sparkle.framework (auto-update). The binary references it via
# @executable_path/../Frameworks (see Package.swift linkerSettings).
SPARKLE=$(find .build/artifacts -type d -name Sparkle.framework -path "*macos*" | head -1)
cp -R "$SPARKLE" "$APP/Contents/Frameworks/"

# Compile the Icon Composer document (Assets/AppIcon.icon, generated by
# Scripts/make-assets.swift) into Assets.car — macOS 26+ renders its Liquid
# Glass appearance live, including the dark/clear/tinted variants — plus a
# fallback AppIcon.icns rendered from the same layers.
ICONBUILD=$(mktemp -d)
# Absolute path on purpose: actool delegates to the ibtoold daemon, which
# caches compilations keyed by the document path as passed.
xcrun actool "$PWD/Assets/AppIcon.icon" --compile "$ICONBUILD" \
    --platform macosx --minimum-deployment-target 26.0 \
    --app-icon AppIcon --output-partial-info-plist "$ICONBUILD/partial.plist" \
    --output-format human-readable-text --errors > /dev/null
cp "$ICONBUILD/Assets.car" "$APP/Contents/Resources/Assets.car"
cp "$ICONBUILD/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
rm -rf "$ICONBUILD"
/usr/libexec/PlistBuddy -c "Add :CFBundleIconFile string AppIcon" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Add :CFBundleIconName string AppIcon" "$APP/Contents/Info.plist"

# With CODESIGN_IDENTITY set (e.g. "Developer ID Application"), produce a
# distributable, notarization-ready signature (hardened runtime + timestamp).
# Otherwise fall back to ad-hoc, which is fine locally.
if [[ -n "${CODESIGN_IDENTITY:-}" ]]; then
    SIGN=(codesign --force --options runtime --timestamp --sign "$CODESIGN_IDENTITY")
else
    # Ad-hoc builds have no Team ID, so hardened runtime's library validation
    # would reject the embedded Sparkle framework. Keep it for distribution.
    SIGN=(codesign --force --options 0 --sign -)
fi

# Sparkle's helpers must be signed individually, innermost first
# (https://sparkle-project.org/documentation/sandboxing/#code-signing).
FW="$APP/Contents/Frameworks/Sparkle.framework"
"${SIGN[@]}" --preserve-metadata=entitlements "$FW/Versions/B/XPCServices/Downloader.xpc"
"${SIGN[@]}" "$FW/Versions/B/XPCServices/Installer.xpc"
"${SIGN[@]}" "$FW/Versions/B/Autoupdate"
"${SIGN[@]}" "$FW/Versions/B/Updater.app"
"${SIGN[@]}" "$FW"
"${SIGN[@]}" "$APP"

echo "Built $APP"

if [[ "${1:-}" == "--install" ]]; then
    pkill -x "$APP_NAME" 2>/dev/null || true
    # 1.0.0 was named ChristmasTree.app
    rm -rf "/Applications/$APP_NAME.app" "/Applications/$BUNDLE_NAME.app"
    cp -R "$APP" /Applications/
    open "/Applications/$BUNDLE_NAME.app"
    echo "Installed /Applications/$BUNDLE_NAME.app"
else
    echo "Run:  open \"$APP\""
fi
